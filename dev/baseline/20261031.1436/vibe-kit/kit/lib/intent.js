'use strict';
/*
 * 用户动作的确定性判断。操作词只是话题，不等于许可；否定、延后、问题讨论和引用先排除。
 * 所有入口复用这里，解析不清时保持原阶段。只处理用户文本，不用模型推断用户是否同意。
 */
function plain(text) {
  return String(text || '').replace(/```[\s\S]*?```/g, '').split('\n').filter((l) => !/^\s*(>|\[vibe-kit)/.test(l)).join('\n').replace(/`[^`]*`/g, '').trim();
}
// 文档的"复验"就是再审一遍（#213"复验 specs"）；复验代码、复验接口还是自测
const DOC_OBJECT = '\\s*(?:一下|一遍|下)?\\s*(?:specs?\\b|proposal\\b|design\\b|tasks\\b|提案|规格|设计|任务清单|需求文档|文档|产物)';
const TOPIC = {
  // "审一下""审审"是最常见的说法（2026-10-16 端到端里用户说"审一下变更 add-export 的代码"没被认出，人工模式反被要求先问）
  // 审查的方式也算要审（#207、#213：提问框选"用 ttls-reviewer 审一次""use ttls-cross-review"）
  review: '(?:审查|审核|复审|审提案|审代码|重新审查|再次审查|审一下|审一审|审审|审(?:一次|一遍|一轮)|再审(?:一次|一遍|一下)?|(?:做|跑|来)(?:一次|一下|个)?(?:代码|提案)?审查|复验(?=' + DOC_OBJECT + ')|(?:ttls-)?cross-review\\b|(?:ttls-)?reviewer\\b)',
  // 起服务也算自测（2026-10-16）：用户说"把服务起起来""启动项目"就是明确要求。编译、构建、快检不算（编译直接跑，不用许可）
  test: '(?:自测|测试|验证|复验(?!' + DOC_OBJECT + ')|看页面|运行测试|执行测试|起服务|启动(?:一下)?(?:服务|项目|应用)|运行(?:一下)?(?:服务|项目|应用)|跑起来|起起来|跑(?:一下|下)?(?:单元|集成|接口)?测试|看(?:一下|下|看)?页面|测(?:一下|一测)(?![^，,。；;\\n]{0,6}(?:想法|思路)))',
  // "开始实施""实施吧""执行任务"（#227、问题反馈表第 8 条：说"开始实施"认不出开工，Apply 自动开着也照人工走）；"实施方案""实施计划"说的是文档，不算
  apply: '(?:apply\\b|开工|开干|开搞|开始(?:做|实现|开发|执行|写代码)|实施(?!\\s*(?:方案|计划|步骤|细节|范围|阶段|情况|文档|说明))|(?:执行|做)(?:这些|剩下的)?任务(?!清单)|(?:按(?:照)?|照|依)(?:提案|任务|清单|方案)(?:做|实现|开发|实施)|做吧|干吧|实现吧|执行吧)',
  commit: '(?:提交|commit\\b)', archive: '(?:归档|archive\\b)', push: '(?:推送|push\\b|推到远端)',
  reviewBudget: '(?:(?:重新开启|重开|重置|新开|再开|开启新的)[^，,。；;!?？\\n]{0,20}审查预算|重新审查|再次审查|再审查|审核一下|审查一下)',
  reviewSkip: '(?:跳过(?:提案|代码|跨模型)?(?:复审|审查)|不(?:做|再做)?(?:提案|代码|跨模型)?(?:复审|审查)|不审了)',
  reviewAccept: '(?:接受(?:这条|该条|成立的)?(?:审查)?(?:问题|风险|意见)|(?:这条|该条)(?:审查意见)?不改)',
  handover: '(?:交接(?!记录|文档|说明)|handover\\b|(?:写|生成|更新|整理)(?:一份|个)?\\s*交接(?:记录|文档|说明))',
  accept: '(?:自测(?:通过|没问题|满意|好了)|验收(?:通过|没问题|满意))',
};
const PREFIX = '(?:(?:请|帮我|现在|直接|立即|及时|继续|顺便|可以|同意|确认|执行|开始|进行|再|然后|最后|接着|先)\\s*)*';
// 先改后做（2026-10-30，审核 R5：用户说"改完提交并推送"，提交认不出）："改完提交""修好再推送""测完归档"。
// permissions.js 的 DEFERRED 本来就按这类说法登记（开口时不登记版本，真正提交时再登记），以前这里却认不出来
const DONE_THEN = '(?:改|修|做|弄|写|搞|测|审|自测|处理|跑|弄)(?:完|好)(?:了)?\\s*(?:就|再|后|之后|以后|然后)?\\s*';
// 只给审查、自测用（认漏了只是多问一次；提交、推送、归档的认法只能收紧）：
//   "跑复验""做次复验""来一遍审查""先跑测试"——动作词前面的动词和量词（#210）
//   "全量自测""按 tasks.md 自测""后端 + 页面自测""用 ttls-reviewer 审一次"——动作词前面的范围（2026-10-21 定的）
const DO = '(?:(?:先|再|重新)?\\s*(?:跑|做|来|走|过|搞)\\s*(?:一下|下|一次|一遍|一轮|次|遍|个|轮)?\\s*)';
const SCOPE = '(?:(?:全量|全部|完整|整体|单元|集成|接口|后端|前端|页面|回归|冒烟|安装|端到端|e2e|功能|代码|这个范围的?|这几个|这些|(?:按|照|依|用|使用|按照)\\s*[^，,。；;！!?？\\n]{1,30}?)\\s*(?:[+＋、和与及/]\\s*)?)';
// 提交只补直接写命令的："git commit""git add/commit""git add 然后 git commit"（2026-10-21 定的）
const GIT_COMMIT = '(?:git\\s+(?:-C\\s+\\S+\\s+)?(?:add\\b[^，,。；;\\n]{0,60}?(?:\\/|然后|再|和|并|&&|;)\\s*(?:git\\s+(?:-C\\s+\\S+\\s+)?)?)?)';
// "合并成1条推送""合并成一条 push"：套件的合并推送工具 2026-10-28 去掉了（用户定的），这种说法照旧算说了推送；用户要合并，Claude 照他说的用 git 自己合，不拦
const SQUASH_PUSH = '(?:把\\s*(?:所有|全部|这些|这几条)?\\s*(?:没推的|没推送的|未推送的|本地的)?\\s*(?:提交)?\\s*)?合并成\\s*(?:1|一)\\s*(?:条|个)\\s*(?:提交)?\\s*(?:再|然后|后|并|并且)?\\s*(?:push\\b|推送|推上去|推(?![送上]))';
// 动作词后面跟着这些词，说的是那件事本身（"审查报告""测试用例"），不是要做。只加不会误伤的词：不加"代码"，"提交代码"是明确要求
// "推送有问题""审查不对"：在抱怨那件事，不是要做（提问框的答案不要求在句首，靠它排除，2026-10-25）
const NOUN = '(?:策略|机制|时机|规则|规范|逻辑|检查|权限|功能|提示|失败|报错|问题|有问题|有毛病|不对|不行|出错|出了问题|日志|脚本|命令|配置|结果|状态|记录|成功|完成|被|测试|的|的时候|时|过|了|是不是|怎么样|报告|意见|用例|环境|太慢|很慢|速度)';
const WANT_SEE = /(?:我|咱们|我们)?(?:要|想|得|准备|打算|来)\s*(?:看看|看一下|看下|瞧瞧|用用|用一下|试试|试一下|访问|打开|点点)\s*(?:系统|页面|界面|效果|网站|前端)(?!\s*(?:的)?\s*(?:设计|文档|架构|代码|说明|日志|配置|源码|结构|需求))|(?:给我|帮我|让我)\s*(?:打开|起|启动|跑)\s*(?:一下)?\s*(?:系统|页面|服务|项目)(?!\s*(?:里|中|下|的|目录|文件|代码|文档|配置))|(?:服务|系统|项目)(?:都)?(?:起|启动|跑)(?:着|了|起来了)(?:吗|没|没有)[^。！!\n]{0,6}(?:我|要|想)\s*(?:看|用|试|访问)/;
function denied(text, action) {
  const op = TOPIC[action];
  if (!op) return true;
  const s = plain(text);
  // "提交前我再看看"：动作词紧跟"前"是在说那之前的事（"提交前端代码"不算）
  const no = new RegExp('(?:先别|不要|不用|不能|不准|不必|无需|先不|暂不|暂时不|不急着|不着急|还不能|还不要|不可以|不让|不要再|取消)[^，,。；;！!\\n]{0,10}' + op + '|' + op + '[^，,。；;！!\\n]{0,12}(?:先缓缓|先别|不要|暂缓|先等|等一下|晚点|稍后|以后再说|等等|还没|之前|以前)|' + op + '\\s*前(?![端台面])|(?:是否|要不要|能不能|可不可以)[^，,。；;！!\\n]{0,6}' + op + '|' + op + '[^，,。；;！!\\n]{0,20}(?:[？?]|怎么|怎样|如何|什么|为什么|会不会|我自己|我来|留给我)', 'i');
  return no.test(s) || /^(?:暂停|先停|等等|等一下|取消)[\s，,。！!]/.test(s);
}
function explicit(text, action) {
  const s = plain(text);
  const op = TOPIC[action];
  if (!s || !op || denied(s, action)) return false;
  const direct = new RegExp('(?:^|[，,。；;\\n])\\s*(?:\\d+[.、]\\s*)?' + PREFIX + op + '(?!\\s*' + NOUN + ')', 'i');
  if (direct.test(s)) return true;
  if ((action === 'review' || action === 'test') && new RegExp('(?:^|[，,。；;\\n])\\s*(?:\\d+[.、]\\s*)?' + PREFIX + DO + '?' + SCOPE + '*' + DO + '?' + op + '(?!\\s*' + NOUN + ')', 'i').test(s)) return true;
  if (action === 'commit' && new RegExp('(?:^|[，,。；;\\n])\\s*(?:\\d+[.、]\\s*)?' + PREFIX + GIT_COMMIT + op + '(?!\\s*' + NOUN + ')', 'i').test(s)) return true;
  if (action === 'reviewSkip' && new RegExp('(?:^|[，,。；;\\n])\\s*(?:这次|本次|我决定|决定)?\\s*' + op + '(?!\\s*' + NOUN + ')', 'i').test(s)) return true;
  if (action !== 'apply' && new RegExp('^(?:请)?(?:把|将)[^，,。；;！!?？\\n]{1,48}' + op + '\\s*(?:吧|一下|一次)?[\\s。！!]*$', 'i').test(s)) return true;
  // "服务都起着吗，我要看看系统""我想看一下页面""给我打开系统用用"：要它把服务起起来给自己看（问题表第 27 条，2026-10-31）。
  // 起服务算自测，以前这类话认不出，钩子让它先问，它就一连问"要启动吗、启动哪些、确定吗"
  if (action === 'test' && WANT_SEE.test(s) && !/(?:别|不要|不用|先不|先别|暂时不)\s*(?:起|启动|跑|开)/.test(s)) return true;
  if (action === 'push' && /(?:^|[，,。；;\n])\s*(?:请|帮我|现在|直接|可以|同意|确认|及时)*\s*提交\s*(?:并|和|后|然后|再)\s*(?:push\b|推送)(?!\s*(?:策略|机制|规则|功能|问题))/i.test(s)) return true;
  if (action === 'push' && /^(?:(?:请|现在|确认|同意|可以)\s*)*(?:合并\s*(?:push|推送)|(?:按(?:照)?|照)(?:这个|刚才的|上面的)?计划\s*(?:合并\s*)?(?:push|推送))[\s。！!]*$/i.test(s)) return true;
  if (action === 'push' && new RegExp('(?:^|[，,。；;\\n])\\s*(?:(?:请|现在|直接|确认|同意|可以|帮我)\\s*)*' + SQUASH_PUSH + '(?!\\s*' + NOUN + ')', 'i').test(s)) return true;
  if (['commit', 'push', 'archive'].includes(action) && new RegExp(DONE_THEN + op + '(?!\\s*' + NOUN + ')', 'i').test(s)) return true;
  // "可以提交了""可以推送了""可以归档了"：句末的"了"是在说现在可以做了（NOUN 里的"了"排除的是"提交了吗""推送了"这种说已经发生的）
  if (action !== 'apply' && new RegExp('(?:^|[，,。；;\\n])\\s*(?:那就|现在|好了?|行了?)?\\s*(?:可以|能)\\s*' + op + '\\s*了[\\s。！!]*$', 'i').test(s)) return true;
  // "推吧""推上去""把这几笔推上去"：单字"推"只认这几种句式（"推断""推荐"不算）
  if (action === 'push' && (/(?:^|[，,。；;\n])\s*(?:那就|好|好的|行|可以|直接)?[，,\s]*推(?:吧|一下|上去|到远端)(?:吧)?[\s。！!]*$/.test(s) || /(?:把|将)[^，,。；;！!?？\n]{1,30}推(?:上去|到远端)/.test(s))) return true;
  // 常见收尾："改好了，提交"；"自测没问题，归档吧"；带前置修改的明确执行指令。
  const then = new RegExp('(?:然后|之后|以后|再|后|并且|并|和)\\s*' + op + '(?!\\s*' + NOUN + ')', 'i');
  if (then.test(s) && !/(?:解释|讲解|举例|讨论|听说|他说|你说|之前说|之前会)/.test(s)) return true;
  // "修完审一下""改好跑一下测试"：只放宽审查和自测（认漏了只是多问一次）；提交、推送、归档的认法只能收紧
  if ((action === 'review' || action === 'test') && new RegExp('(?:完|好)\\s*' + op + '(?!\\s*' + NOUN + ')', 'i').test(s) && !/(?:解释|讲解|举例|讨论|听说|他说|你说)/.test(s)) return true;
  if (action === 'apply') {
    if (/\bapply\b.*(?:功能|流程|命令|机制|时候|阶段|怎么|是否)|(?:提案|需求|规格|设计|任务清单|验法).*(?:修改|调整|改一下|不对|讨论)/i.test(s)) return false;
    return /(?:把|将)?\s*(?:任务\s*)?(?:\d+\.\d+|第\s*\d+\s*项)[^，,。！!?？\n]{0,12}(?:做了|做完|实现|开发|打勾)|^(?:按照现在的方案修改|开始吧|可以开始了|可以(?:做|开工|实现)了)[\s。！!]*$/i.test(s);
  }
  return false;
}
/**
 * 用户要把没推的提交合并了再推（"合并推送""合并成1条推送""把这几条合并成一条再 push"）。套件不再有合并推送工具（2026-10-28），
 * 用户这么说的，Claude 照他说的用 git 自己合（reset --soft、rebase），合并时重新提交算在这句话里，不再要"提交"许可（用户 2026-10-28 补充）
 */
function mergeIntent(text) {
  const s = plain(text);
  return new RegExp(SQUASH_PUSH, 'i').test(s) || /合并\s*(?:push|推送)|合并(?:成|为)\s*(?:1|一)\s*(?:条|个)/i.test(s);
}
/** 话里有没有提到这件事（提问框的问题用）：不管是不是要做 */
function has(text, action) { const op = TOPIC[action]; return !!op && new RegExp(op, 'i').test(plain(text)); }
/** 话里有这件事的动作词、而且不是在说那件事本身（"审查报告""测试失败"）：提问框的答案用，不要求在句首 */
function mentions(text, action) { const op = TOPIC[action]; return !!op && new RegExp(op + '(?!\\s*' + NOUN + ')', 'i').test(plain(text)); }
module.exports = { plain, explicit, denied, has, mentions, mergeIntent };
