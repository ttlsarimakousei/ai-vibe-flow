'use strict';
/* #87、#92、#93：真人跳过或接受问题与完整审查分别登记，取消、其它目标与新代码仍不借旧决定。 */
const path = require('path'); const H = require('./lib/harness');
const h = H.makeHome('feedback1013-decisions', process.argv[2]);
const p = H.makeRepo(path.join(h.work, 'p'), { '.gitignore': '.vibe/\n', 'a.js': 'let a=1;\n', 'openspec/changes/add-a/tasks.md': '- [x] 1.1 修改 a.js；验：node --check a.js\n- [ ] 2.1 [代码审查] 独立审查；验：完整结果\n- [ ] 2.2 [审查意见处理] 逐条处理；验：复验结果\n' });
const d = path.join(p, 'openspec/changes/add-a'); const cli = path.join(h.kit, 'tools/review.js'); const S = require(path.join(h.kit, 'lib/session')); const R = require(path.join(h.kit, 'lib/review-runner'));
let n = 0; const tf = (es) => H.transcript(path.join(h.root, 't' + (++n) + '.jsonl'), es);
const q = (s) => '"' + s.replace(/\\/g, '/') + '"';
const command = 'node ' + q(cli) + ' waive --project ' + q(p) + ' --change add-a --mode code --reason "用户已经实测并明确决定本轮跳过代码审查"';
const guard = (cmd, text) => H.hook(h, 'guard-commit', { cwd: p, session_id: 'decision', hook_event_name: 'PreToolUse', tool_name: 'Bash', tool_use_id: 'decision-op', transcript_path: tf([H.tr.user(text)]), tool_input: { command: cmd } });
H.ok('没有用户决定不能跳过审查', guard(command, '继续') !== null);
H.ok('真正跳过决定可执行', guard(command, '这次跳过代码审查，归档 add-a') === null, guard(command, '这次跳过代码审查，归档 add-a'));
H.ok('取消跳过仍拦截', guard(command, '不要跳过代码审查') !== null);
H.ok('包装命令也不能借无许可跳过', guard('cmd /c ' + command, '继续') !== null);
const result = H.node(h, cli, ['waive', '--project', p, '--change', 'add-a', '--mode', 'code', '--reason', '用户已经实测并明确决定本轮跳过代码审查']);
H.ok('人工放弃直接结束', result.code === 0 && JSON.parse(result.out).status === 'dismissed', result);
H.ok('跳过不伪造审查通过', !S.codeReviewed(d) && !S.reviewRecord('code', d));
H.ok('放弃不往团队任务追加记录', !H.read(path.join(d, 'tasks.md')).includes('用户决定跳过审查'));
H.ok('放弃不算代码审查通过', S.codeReviewIssue(d) !== '');
H.ok('跳过状态跨会话保留', S.GLOBAL_STATE.test('review-waivers.json'));
H.write(path.join(p, 'a.js'), 'let a=2;\n');
H.ok('新代码使旧跳过记录失效', S.codeReviewIssue(d) !== '');
const file = path.join(h.root, 'decisions.json'); H.write(file, JSON.stringify({ findings: [{ id: 'r1', action: 'accepted', reason: '用户在当前输入明确决定保留这条已核实的问题' }] }));
S.recordReview('code', d, 1, 'compat-issue', Date.now()); S.updateState('reviewed', (o) => { o[S.normKey(d)].executor = 'agent'; });
const resolve = 'node ' + q(cli) + ' resolve --project ' + q(p) + ' --change add-a --decisions ' + q(file);
H.ok('接受问题也要真人决定', guard(resolve, '继续') !== null);
H.ok('接受审查风险可登记意见处理', guard(resolve, '接受审查风险 add-a') === null, guard(resolve, '接受审查风险 add-a'));
const accepted = H.node(h, cli, ['resolve', '--project', p, '--change', 'add-a', '--decisions', file]);
H.ok('兼容审查可记录用户接受问题', accepted.code === 0 && S.reviewRecord('code', d).resolved && S.reviewRecord('code', d).decisions[0].action === 'accepted', accepted);
H.done('1013 用户审查决定');
