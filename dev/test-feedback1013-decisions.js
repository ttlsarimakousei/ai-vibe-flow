'use strict';
/* #92、#93：真人接受问题与完整审查分别登记，其它目标与新代码不借旧决定。 */
const path = require('path'); const H = require('./lib/harness');
const h = H.makeHome('feedback1013-decisions', process.argv[2]);
const p = H.makeRepo(path.join(h.work, 'p'), { '.gitignore': '.vibe/\n', 'a.js': 'let a=1;\n', 'openspec/changes/add-a/tasks.md': '- [x] 1.1 修改 a.js；验：node --check a.js\n' });
const d = path.join(p, 'openspec/changes/add-a'); const cli = path.join(h.kit, 'tools/review.js'); const S = require(path.join(h.kit, 'lib/session')); const R = require(path.join(h.kit, 'lib/review-runner'));
let n = 0; const tf = (es) => H.transcript(path.join(h.root, 't' + (++n) + '.jsonl'), es);
const q = (s) => '"' + s.replace(/\\/g, '/') + '"';
const guard = (cmd, text) => H.hook(h, 'guard-commit', { cwd: p, session_id: 'decision', hook_event_name: 'PreToolUse', tool_name: 'Bash', tool_use_id: 'decision-op', transcript_path: tf([H.tr.user(text)]), tool_input: { command: cmd } });
H.ok('waive 没了', H.node(h, cli, ['waive', '--project', p, '--change', 'add-a', '--mode', 'code']).code !== 0);
H.write(path.join(p, 'a.js'), 'let a=2;\n');
const rp = R.prepare({ cwd: p, change: 'add-a', mode: 'code', base: 'HEAD' });
R.submit(rp.id, rp.agents[0].lens, '审查任务：' + rp.id + '/' + rp.agents[0].lens + '\n{"issues":[{"severity":"P2","file":"a.js","line":1,"problem":"值不对","evidence":"a=2"}],"summary":"看完了"}');
const file = path.join(h.root, 'decisions.json'); H.write(file, JSON.stringify({ findings: [{ id: 'r1', action: 'accepted', reason: '用户在当前输入明确决定保留这条已核实的问题' }] }));
const resolve = 'node ' + q(cli) + ' resolve --project ' + q(p) + ' --change add-a --decisions ' + q(file);
H.ok('接受问题也要真人决定', guard(resolve, '继续') !== null);
H.ok('接受审查风险可登记意见处理', guard(resolve, '接受审查风险 add-a') === null, guard(resolve, '接受审查风险 add-a'));
const accepted = H.node(h, cli, ['resolve', '--project', p, '--change', 'add-a', '--decisions', file]);
H.ok('记录用户接受问题', accepted.code === 0 && S.reviewRecord('code', d).resolved && S.reviewRecord('code', d).decisions[0].action === 'accepted', accepted);
H.write(path.join(p, 'a.js'), 'let a=3;\n');
H.ok('新代码使旧决定失效', S.codeReviewIssue(d) !== '');
H.done('1013 用户审查决定');
