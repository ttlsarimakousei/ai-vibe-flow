'use strict';
/* #72、#77、#83、#86、#90：真实答案、多个变更、范围修订和暂不提交。旧版参数必须检出反例。 */
const path = require('path');
const H = require('./lib/harness');
const h = H.makeHome('feedback1013-workflow', process.argv[2], { autoMode: true });
const p = H.makeRepo(path.join(h.work, 'p'), { '.gitignore': '.vibe/\n', 'a.js': 'let a=1;\n', 'openspec/changes/add-a/tasks.md': '- [ ] 1.1 修改 a.js；验：node --check a.js\n', 'openspec/changes/add-b/tasks.md': '- [ ] 1.1 修改 a.js；验：node --check a.js\n' });
const d = path.join(p, 'openspec/changes/add-a');
const S = require(path.join(h.kit, 'lib/session')); const A = require(path.join(h.kit, 'lib/apply-scope'));
let seq = 0;
const tf = (es) => H.transcript(path.join(h.root, 't' + (++seq) + '.jsonl'), es);
const ask = (q, a) => H.tr.ran('AskUserQuestion', { questions: [{ question: q }] }, 'Your questions have been answered: "' + q + '"="' + a + '"');
const j = { cwd: p, session_id: 'multiple', transcript_path: tf([H.tr.user('准备 add-a 提案'), ask('add-a 能否开工？', '开工')]) };
S.setFlow(j, true, '提案', 'plan');
H.ok('多变更提问点名后选开工可授权', S.confirmApply(j));
H.ok('只绑定问题中指定的变更', !!(S.flowState(j).applyScope || {}).dirs && Object.keys(S.flowState(j).applyScope.dirs).length === 1 && !!S.flowState(j).applyScope.dirs[S.normKey(d)]);
S.setFlow(j, true, '修订提案', 'plan');
H.ok('旧开工答案不能再次授予许可', !S.confirmApply(j));
j.session_id = 'context'; S.setFlow(j, true, '提案', 'plan'); S.flowTouch(j, d);
H.ok('无参数 apply 可绑定唯一当前变更', A.grant(j, '/opsx:apply').ok);
j.session_id = 'ambiguous'; S.setFlow(j, true, '提案', 'plan');
H.ok('没有当前目标时多个变更仍不猜', !A.grant(j, '/opsx:apply').ok);
S.flowTouch(j, d);
H.ok('问题给出多个目标时不借唯一旧目标', !A.grant(j, '开工', 'add-a 或 add-b 能否开工？').ok);
const composite = [H.tr.user('都测试完了，归档吧'), ask('add-a 开工，勾 6.1 并归档？', '开工，勾 6.1 并归档')];
H.ok('复合答案保留归档许可', S.userSaid(composite.flat(), 'archive').ok);
H.ok('复合答案可明确绑定提问目标', /add-a/.test(S.userSaid(composite.flat(), 'archive').targetText || ''));
H.ok('推送问题中的单字推有效', S.userSaid([H.tr.user('继续'), ...ask('是否推送？', '推')], 'push').ok);
H.ok('其它问题单字推不能授权', !S.userSaid([H.tr.user('继续'), ...ask('图形向哪边移动？', '推')], 'push').ok);
H.ok('取消归档优先', !S.userSaid([...composite.flat(), H.tr.user('先别归档')], 'archive').ok);
H.ok('否定复合答案不授权', !S.userSaid([H.tr.user('继续'), ...ask('是否归档？', '开工，但不要归档')], 'archive').ok);
j.session_id = 'scope'; S.setFlow(j, true, '开工', 'apply'); A.grant(j, '开工 add-a');
H.write(path.join(d, 'proposal.md'), '新的需求范围\n');
H.ok('失效范围仍禁止业务代码', !!A.check(j, path.join(p, 'a.js')));
const revision = { ...j, tool_name: 'Edit', tool_input: { file_path: path.join(d, 'revisions.md'), old_string: '', new_string: '修订依据' } };
if (A.prepareEdit) A.prepareEdit(revision, revision.tool_input.file_path);
H.ok('范围失效时允许回到提案补修订', A.check(j, revision.tool_input.file_path) === '' && S.flowState(j).stage === 'plan' && !S.flowState(j).applyScope);
H.ok('回到提案修订仍不允许业务代码', !!A.check(j, path.join(p, 'a.js')));
S.setFlow(j, true, '重新开工', 'apply'); A.grant(j, '开工 add-a'); H.write(path.join(d, 'proposal.md'), '再调整范围\n');
const tick = { ...j, tool_input: { old_string: '[ ]', new_string: '[x]' } };
if (A.prepareEdit) A.prepareEdit(tick, path.join(d, 'tasks.md'));
H.ok('任务打勾不能借修订入口逃过范围锁', !!A.check(j, path.join(d, 'tasks.md')));
const declined = [H.tr.user('先不提交')]; const cj = { cwd: p, session_id: 'declined' };
H.ok('明确暂不提交可收工', typeof S.commitDeclined === 'function' && S.commitDeclined(cj, declined));
H.ok('同一份改动不反复催提交', typeof S.commitDeclined === 'function' && S.commitDeclined(cj, declined));
H.write(path.join(p, 'a.js'), 'let a=2;\n');
H.ok('新改动不借用旧暂不提交选择', typeof S.commitDeclined === 'function' && !S.commitDeclined(cj, declined));
H.ok('不把提交讨论当拒绝提交', typeof S.commitDeclined === 'function' && !S.commitDeclined(cj, [H.tr.user('提交机制不对')]));
H.done('1013 开工、范围与确认');
